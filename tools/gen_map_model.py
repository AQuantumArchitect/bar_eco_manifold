#!/usr/bin/env python3
"""
Generate src/maps/supremeIsthmus.js from the public maps-metadata entry for
Supreme Isthmus v2.1 (id ACgCe99NC8yZFecMwRCm).

Run from project root:
    python3 tools/gen_map_model.py                 # fetch map_list.yaml from GitHub
    python3 tools/gen_map_model.py path/to/map_list.yaml
Requires PyYAML.

Data source: https://github.com/beyond-all-reason/maps-metadata (Apache-2.0).
"""
import sys
import urllib.request
from pathlib import Path

import yaml

MAP_ID = "ACgCe99NC8yZFecMwRCm"
URL = "https://raw.githubusercontent.com/beyond-all-reason/maps-metadata/main/map_list.yaml"
OUT = Path(__file__).parent.parent / "src" / "maps" / "supremeIsthmus.js"

# Not in map_list.yaml; taken from issue #11. 1 map unit = 512 elmos (Spring engine map-size convention).
MAP_UNITS = 24
ELMOS_PER_MAP_UNIT = 512


def load():
    if len(sys.argv) > 1:
        return yaml.safe_load(Path(sys.argv[1]).read_text())
    with urllib.request.urlopen(URL) as r:
        return yaml.safe_load(r.read())


def main():
    entry = load()[MAP_ID]
    assert entry["springName"] == "Supreme Isthmus v2.1", entry["springName"]
    start = entry["startPos"]
    positions = start["positions"]
    seats = {}
    for team, side in enumerate(start["team"][0]["sides"]):
        for s in side["starts"]:
            p = positions[s["spawnPoint"]]
            seats[s["spawnPoint"]] = {"x": p["x"], "z": p["y"], "team": team, "role": s["role"]}
    assert len(seats) == 16
    seats = {k: seats[k] for k in sorted(seats, key=lambda k: int(k[1:]))}
    size = MAP_UNITS * ELMOS_PER_MAP_UNIT

    lines = []
    for k, v in seats.items():
        lines.append(f"    {k}: {{ x: {v['x']}, z: {v['z']}, team: {v['team']}, role: '{v['role']}' }},")
    seat_js = "\n".join(lines)

    OUT.write_text(f"""// GENERATED by tools/gen_map_model.py -- do not edit by hand.
// Data: beyond-all-reason/maps-metadata map_list.yaml (Apache-2.0), entry {MAP_ID}.
// Positions are Spring world coords in elmos; metadata's `y` is the map's z axis.
// Team 0 = P1..P8, team 1 = P9..P16 (from startPos.team[0].sides order).

export const supremeIsthmus = {{
  id: '{MAP_ID}',
  springName: '{entry['springName']}',
  // {MAP_UNITS}x{MAP_UNITS} map units, 1 map unit = {ELMOS_PER_MAP_UNIT} elmos (Spring engine map-size convention).
  // The size is not in map_list.yaml; it is taken from issue #11.
  sizeElmos: {{ x: {size}, z: {size} }},
  seats: {{
{seat_js}
  }},
  // Named waypoints for the Pond Turtle push (issues #15, #23). Picked by eye from the public minimap
  // (maps-metadata map_list.yaml `photo` supreme2.1mini.png, 1380 px = 12288 elmos, ~8.9 elmos/px,
  // px (x, y) -> elmos (x, z)); no private data. Approximate on purpose: transit adds a pathFactor.
  // pond: centre of the landlocked crater lake inside team 0's land; the lake spans minimap
  //   px x 195-365, y 980-1070, i.e. elmos x 1740-3250, z 8730-9530. Seat P4 is ~1.15k elmos north.
  // seaEntry: south shore of the north-west sea's bay, north of the lake rim (minimap px 440, 780).
  //   Amphibious units walk pond -> seaEntry over land; only seaEntry -> enemyBeach is water.
  // midSea: open water of that same north-west sea (minimap px 520, 620).
  // enemyBeach: grey beach on that sea's eastern shore, below team 1's land (minimap px 680, 440).
  waypoints: {{
    pond: {{ x: 2490, z: 9130 }},
    seaEntry: {{ x: 3918, z: 6945 }},
    midSea: {{ x: 4630, z: 5521 }},
    enemyBeach: {{ x: 6055, z: 3918 }},
  }},
  // Waypoints that are enclosed water: ships and other non-amphibious units cannot leave them.
  landlocked: ['pond'],
  source: {{
    repo: 'https://github.com/beyond-all-reason/maps-metadata',
    file: 'map_list.yaml',
    entry: '{MAP_ID}',
    license: 'Apache-2.0',
  }},
}};
""")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
